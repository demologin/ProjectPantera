package com.javarush.ushanov.repository;

import com.javarush.ushanov.entity.QuestStep;
import com.javarush.ushanov.entity.StepStatus;

import java.util.HashMap;
import java.util.Map;
import java.util.Optional;

/**
 * Репозиторий квеста — хранит все шаги квеста в памяти (в Map).
 */
public class QuestRepository {

    /** Все шаги квеста: ключ — id шага, значение — объект QuestStep */
    private final Map<Integer, QuestStep> steps = new HashMap<>();

    /** id первого шага, с которого начинается игра */
    public static final int START_STEP_ID = 1;

    public QuestRepository() {
        initQuest();
    }

    /**
     * Логика квеста в виде дерева шагов.
     *
     * Сюжет: игрок — пилот разведывательного корабля.
     * Корабль получил сигнал бедствия от неизвестной станции.
     *
     * Дерево решений:
     *
     * [1] Принять сигнал?
     *   -> "Принять сигнал"       => [2]
     *   -> "Игнорировать сигнал"  => [3] LOSE
     *
     * [2] Пристыковаться к станции?
     *   -> "Пристыковаться"        => [4]
     *   -> "Остаться на орбите"    => [5] LOSE
     *
     * [4] Что делать на станции?
     *   -> "Исследовать реактор"   => [6] LOSE
     *   -> "Найти команду"         => [7]
     *
     * [7] Команда предлагает улететь вместе. Взять всех?
     *   -> "Взять всех"            => [8] WIN
     *   -> "Взять только капитана" => [9] LOSE
     */
    private void initQuest() {

        // Шаг 1 — начало
        steps.put(1, QuestStep.builder()
                .id(1)
                .description("Ты — пилот разведывательного корабля «Аврора». " +
                        "В пустоте космоса твой бортовой компьютер фиксирует слабый сигнал бедствия. " +
                        "Источник — заброшенная исследовательская станция «Кеплер-7». " +
                        "Что ты будешь делать?")
                .status(StepStatus.PLAYING)
                .options(Map.of(
                        "Принять сигнал и изменить курс", 2,
                        "Игнорировать — миссия важнее", 3
                ))
                .build());

        // Шаг 2 — приближаемся к станции
        steps.put(2, QuestStep.builder()
                .id(2)
                .description("Ты изменил курс и приближаешься к станции «Кеплер-7». " +
                        "Внешне она выглядит повреждённой — несколько секций разгерметизированы. " +
                        "Однако стыковочный модуль, кажется, работает. " +
                        "Твои действия?")
                .status(StepStatus.PLAYING)
                .options(Map.of(
                        "Пристыковаться и войти на станцию", 4,
                        "Остаться на орбите и попытаться выйти на связь", 5
                ))
                .build());

        // Шаг 3 — ПОРАЖЕНИЕ: проигнорировал сигнал
        steps.put(3, QuestStep.builder()
                .id(3)
                .description("Ты проигнорировал сигнал и продолжил миссию. " +
                        "Спустя несколько часов ты узнал из новостей: выжившие со станции «Кеплер-7» " +
                        "были обнаружены мёртвыми. Ты мог их спасти... " +
                        "Командование отстранило тебя от полётов.")
                .status(StepStatus.LOSE)
                .options(Map.of())
                .build());

        // Шаг 4 — на станции
        steps.put(4, QuestStep.builder()
                .id(4)
                .description("Ты на борту станции. Воздух разреженный, аварийное освещение мигает. " +
                        "Датчики показывают двух выживших в жилом модуле. " +
                        "Но также фиксируется нестабильность реактора. " +
                        "Что исследовать первым?")
                .status(StepStatus.PLAYING)
                .options(Map.of(
                        "Срочно проверить реактор", 6,
                        "Найти выживших в жилом модуле", 7
                ))
                .build());

        // Шаг 5 — ПОРАЖЕНИЕ: остался на орбите
        steps.put(5, QuestStep.builder()
                .id(5)
                .description("Ты пытался выйти на связь несколько часов, но ответа не было. " +
                        "Пока ты медлил, реактор станции вышел из строя. " +
                        "Мощный взрыв уничтожил станцию вместе со всеми выжившими. " +
                        "Нужно было действовать быстрее.")
                .status(StepStatus.LOSE)
                .options(Map.of())
                .build());

        // Шаг 6 — ПОРАЖЕНИЕ: пошёл к реактору
        steps.put(6, QuestStep.builder()
                .id(6)
                .description("Ты направился к реактору, но не успел дойти — " +
                        "перегрузка системы вызвала разрыв трубопровода. " +
                        "Радиоактивный пар заполнил коридор. " +
                        "Ты получил критическую дозу облучения. " +
                        "Выживших найти не удалось.")
                .status(StepStatus.LOSE)
                .options(Map.of())
                .build());

        // Шаг 7 — нашли выживших
        steps.put(7, QuestStep.builder()
                .id(7)
                .description("Ты нашёл двух выживших: капитана Марину Волкову и бортинженера Алекса Рида. " +
                        "Они истощены, но в сознании. Капитан говорит: " +
                        "«Нас трое — мой напарник застрял в заблокированном отсеке, " +
                        "но корабль может принять только двух пассажиров». " +
                        "Что решаешь?")
                .status(StepStatus.PLAYING)
                .options(Map.of(
                        "Забрать обоих — найдём способ", 8,
                        "Взять только капитана — она важнее для расследования", 9
                ))
                .build());

        // Шаг 8 — ПОБЕДА
        steps.put(8, QuestStep.builder()
                .id(8)
                .description("Ты нашёл решение: один из выживших может разместиться в грузовом отсеке. " +
                        "Немного тесновато, зато все живы! " +
                        "«Аврора» отстыковалась от станции за минуту до того, как реактор взорвался. " +
                        "Оба выживших доставлены на базу. " +
                        "Командование объявило тебя героем. Миссия выполнена!")
                .status(StepStatus.WIN)
                .options(Map.of())
                .build());

        // Шаг 9 — ПОРАЖЕНИЕ: бросил инженера
        steps.put(9, QuestStep.builder()
                .id(9)
                .description("Ты взял только капитана и улетел. " +
                        "Бортинженер Алекс Рид погиб при взрыве реактора. " +
                        "Капитан Волкова так и не простила тебя. " +
                        "На базе тебя ждал трибунал за нарушение устава: " +
                        "«Не оставляй своих». Конец карьеры.")
                .status(StepStatus.LOSE)
                .options(Map.of())
                .build());
    }

    /**
     * Получить шаг по id.
     */
    public Optional<QuestStep> findById(int id) {
        return Optional.ofNullable(steps.get(id));
    }

    public int getStartStepId() {
        return START_STEP_ID;
    }

    /** Общее количество шагов в квесте (для тестов) */
    public int size() {
        return steps.size();
    }
}
